#!/usr/bin/env node
// Regenerates the typed ABI modules used by the keeper and the frontend from Foundry's build output.
// Run `forge build` in ./contracts first, then `node scripts/export-abis.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = ["PerpEngine", "EngineLens", "HouseVault", "RewardToken", "PublisherOracle", "TestUSDC"];
const targets = ["keeper/src/abi.ts", "frontend/src/lib/abi.ts"];

const lower = (name) => name[0].toLowerCase() + name.slice(1);
let out = "// Generated by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8"));
  out += `\nexport const ${lower(name)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}
for (const target of targets) {
  const path = join(root, target);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, out);
  console.log(`wrote ${target}`);
}
