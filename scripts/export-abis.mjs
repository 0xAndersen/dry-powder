#!/usr/bin/env node
// Regenerates the ABI modules used by the frontend, the keeper and the MCP server from Foundry's build output.
// Run `forge build` in ./contracts first, then `node scripts/export-abis.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// [contract, source file] (both factory and account live in AgentAccount.sol)
const contracts = [
  ["PerpEngine", "PerpEngine"],
  ["EngineLens", "EngineLens"],
  ["HouseVault", "HouseVault"],
  ["RewardToken", "RewardToken"],
  ["PublisherOracle", "PublisherOracle"],
  ["PythOracle", "PythOracle"],
  ["TestUSDC", "TestUSDC"],
  ["AgentAccount", "AgentAccount"],
  ["AgentAccountFactory", "AgentAccount"],
  ["TrailingStops", "TrailingStops"],
  ["TwapOrders", "TwapOrders"],
  ["PrizeDistributor", "PrizeDistributor"],
  ["Strategies", "Strategies"],
  ["AgentRegistry", "AgentRegistry"],
];
const targets = [
  ["frontend/src/lib/abi.ts", "ts"],
  ["sdk/src/abi.ts", "ts"],
  ["mcp/src/abi.mjs", "js"],
  ["keeper/src/abi.mjs", "js"],
];

const lower = (name) => name[0].toLowerCase() + name.slice(1);
const read = (name, file) => JSON.parse(readFileSync(join(root, "contracts/out", `${file}.sol`, `${name}.json`), "utf8")).abi;
// The engine is one address and two contracts: PerpEngine forwards whatever it does not define to PerpEngineExt by
// delegatecall. Callers see the union: PerpEngine's entries, then the extension's functions, events and errors
// that PerpEngine does not already have (the extension's constructor is its own).
const signature = (x) => `${x.type}:${x.name ?? ""}(${(x.inputs ?? []).map((i) => i.type).join(",")})`;
function engineAbi() {
  const core = read("PerpEngine", "PerpEngine");
  const seen = new Set(core.map(signature));
  const ext = read("PerpEngineExt", "PerpEngineExt").filter((x) => ["function", "event", "error"].includes(x.type) && !seen.has(signature(x)));
  return [...core, ...ext];
}
const abis = contracts.map(([name, file]) => [name, JSON.stringify(name === "PerpEngine" ? engineAbi() : read(name, file), null, 2)]);
for (const [target, kind] of targets) {
  let out = "// Generated by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n";
  for (const [name, abi] of abis) out += `\nexport const ${lower(name)}Abi = ${abi}${kind === "ts" ? " as const" : ""};\n`;
  const path = join(root, target);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, out);
  console.log(`wrote ${target}`);
}
