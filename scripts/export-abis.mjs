#!/usr/bin/env node
// Regenerates the ABI modules used by the frontend, the keeper and the MCP server from Foundry's build output.
// Run `forge build` in ./contracts first, then `node scripts/export-abis.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// [contract, source file] (both factory and account live in AgentAccount.sol)
const contracts = [
  ["PerpEngine", "PerpEngine"],
  ["EngineLens", "EngineLens"],
  ["HouseVault", "HouseVault"],
  ["RewardToken", "RewardToken"],
  ["PublisherOracle", "PublisherOracle"],
  ["PythOracle", "PythOracle"],
  ["TestUSDC", "TestUSDC"],
  ["AgentAccount", "AgentAccount"],
  ["AgentAccountFactory", "AgentAccount"],
  ["TrailingStops", "TrailingStops"],
  ["TwapOrders", "TwapOrders"],
];
const targets = [
  ["frontend/src/lib/abi.ts", "ts"],
  ["sdk/src/abi.ts", "ts"],
  ["mcp/src/abi.mjs", "js"],
  ["keeper/src/abi.mjs", "js"],
];

const lower = (name) => name[0].toLowerCase() + name.slice(1);
const abis = contracts.map(([name, file]) => {
  const artifact = JSON.parse(readFileSync(join(root, "contracts/out", `${file}.sol`, `${name}.json`), "utf8"));
  return [name, JSON.stringify(artifact.abi, null, 2)];
});
for (const [target, kind] of targets) {
  let out = "// Generated by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n";
  for (const [name, abi] of abis) out += `\nexport const ${lower(name)}Abi = ${abi}${kind === "ts" ? " as const" : ""};\n`;
  const path = join(root, target);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, out);
  console.log(`wrote ${target}`);
}
